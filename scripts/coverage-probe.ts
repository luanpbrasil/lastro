// Knowledge-graph coverage probe (one-off, measure only: it never edits shared/kg.json or the prompt).
// For each economia/politica video in data/classifier/labels.csv, Claude Haiku lists the schools, thinkers,
// episodes and institutions the content argues from, each marked in-graph (node id) or missing.
//   npm run probe -- --estimate        cost estimate only (no API call)
//   npm run probe -- --run [--limit N] call the API; resumable (skips videos already in .cache/coverage/raw.jsonl)
//   npm run probe -- --report          aggregate into eval/coverage-probe.md ($0)
// The API key is read in-process from .dev.vars; it is never printed or logged.
import Anthropic from "@anthropic-ai/sdk";
import { appendFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { KG, NODE_IDS } from "../shared/kg";
import { costUsd, PRICES } from "../shared/prices";
import { looseNorm } from "../shared/transcript";

const MODEL = "claude-haiku-5-5";
const RAW = "data/classifier/raw";
const OUT = ".cache/coverage";
const RAW_OUT = `${OUT}/raw.jsonl`;
const SPEND = `${OUT}/spend.json`;
const STOP_USD = 0.22; // hard stop; Luan's cap for this probe is $0.25
const CONCURRENCY = 4;

// Same list as scripts/eval.ts section 3: parties and active politicians are never graph concepts.
const FORBIDDEN = ["PT", "PL", "PSDB", "MDB", "PSOL", "Novo", "União Brasil", "Republicanos", "Lula", "Bolsonaro", "Haddad", "Tarcísio", "Alckmin", "Dilma", "Ciro Gomes", "Marina Silva", "Boulos", "Moro", "Lira", "Pacheco", "Motta", "Alcolumbre", "Milei", "Trump", "Flávio Bolsonaro", "Campos Neto", "Galípolo"].map(looseNorm);
const MARK = "<!-- auto: everything below is regenerated by npm run probe -- --report -->";

const TYPES = ["school", "thinker", "episode", "institution"] as const;
const RELS = ["opposes", "derives_from", "proponent_of", "grounds", "justifies", "tested_in", "none"] as const;

function graphText(): string {
  const lines = KG.nodes.map((n) => `- ${n.id} [${n.type}] ${n.name} (também: ${n.aliases.join("; ")}): ${n.summary}`);
  lines.push("", "Relações:", ...KG.edges.map((e) => `- ${e.from} ${e.type} ${e.to}`));
  return lines.join("\n");
}

const SYSTEM = `Você ajuda a medir a cobertura de um grafo de ideias usado para dar contexto a vídeos brasileiros de economia e política.
O grafo mapeia ideias para escolas de pensamento, pensadores, episódios históricos e instituições. Nunca para partidos ou políticos em atividade.

Grafo atual:
${graphText()}

Tarefa: leia o título, a descrição e (se houver) o começo das legendas de um vídeo. Liste os conceitos de que o conteúdo argumenta ou que ele invoca como base de uma afirmação:
- school: escola de pensamento, tradição ou doutrina (econômica, política ou filosófica). Ex.: liberalismo econômico, conservadorismo, marxismo, nacionalismo.
- thinker: pensador ou economista citado como fonte de uma ideia (não jornalistas, apresentadores ou entrevistados comentando).
- episode: episódio histórico usado como prova ou exemplo (crise, plano econômico, regime).
- institution: instituição ou regra cujo papel é debatido (Banco Central, regra fiscal, STF como instituição, sistema eleitoral).

Regras:
- Partidos e políticos em atividade nunca são conceitos. Se o vídeo argumenta a partir da plataforma de um partido ou de um político, registre a tradição por trás (ex.: "conservadorismo", "populismo", "trabalhismo"), não o nome.
- Só conte o que o conteúdo usa como argumento ou base. Notícia factual sem ideia por trás (agenda, bastidores, quem votou em quem) não gera conceito.
- in_graph: o id do nó, se o conceito é um nó do grafo (pelo nome ou por qualquer outro nome dele); senão "none".
- surface: o termo exato que o vídeo usa.
- alias_only: true se o nome é só outra forma de chamar um nó já existente (ex.: um sinônimo, a sigla, ou um pensador cuja ideia citada é exatamente a da escola que já está no grafo); false se é um conceito diferente.
- nearest e relation: para um conceito fora do grafo, o nó existente mais próximo e a relação dele com esse nó (o conceito opposes / derives_from / proponent_of / grounds / justifies / tested_in o nó). "none" se nenhum serve.
- evidence: trecho curto (até 20 palavras) do título, descrição ou legenda que mostra o conceito.
- Se o vídeo não argumenta a partir de nenhuma ideia, devolva concepts vazio.
Responda só com o JSON pedido.`;

const SCHEMA = {
  type: "object",
  additionalProperties: false,
  required: ["topic", "argues_from_ideas", "concepts"],
  properties: {
    topic: { type: "string" },
    argues_from_ideas: { type: "boolean" },
    concepts: {
      type: "array",
      items: {
        type: "object",
        additionalProperties: false,
        required: ["name", "type", "surface", "in_graph", "alias_only", "nearest", "relation", "evidence"],
        properties: {
          name: { type: "string" },
          type: { type: "string", enum: [...TYPES] },
          surface: { type: "string" },
          in_graph: { type: "string", enum: [...NODE_IDS, "none"] },
          alias_only: { type: "boolean" },
          nearest: { type: "string", enum: [...NODE_IDS, "none"] },
          relation: { type: "string", enum: [...RELS] },
          evidence: { type: "string" },
        },
      },
    },
  },
};

interface Video { id: string; title: string; description: string }
interface Caption { status: "ok" | "none"; segments?: { s: number; d: number; t: string }[] }
interface Concept { name: string; type: (typeof TYPES)[number]; surface: string; in_graph: string; alias_only: boolean; nearest: string; relation: string; evidence: string }
interface Row { id: string; captions: boolean; topic: string; argues_from_ideas: boolean; concepts: Concept[]; costUsd: number }

function apiKey(): string {
  const line = readFileSync(".dev.vars", "utf8").split("\n").find((l) => l.startsWith("ANTHROPIC_API_KEY="));
  const key = line?.slice("ANTHROPIC_API_KEY=".length).trim().replace(/^"|"$/g, "");
  if (!key) throw new Error(".dev.vars has no ANTHROPIC_API_KEY");
  return key;
}

function videos(): { v: Video; captions: string }[] {
  const all: Record<string, Video> = JSON.parse(readFileSync(`${RAW}/videos.json`, "utf8"));
  const lines = readFileSync("data/classifier/labels.csv", "utf8").trim().split("\n");
  const head = lines[0].split(",");
  const col = (r: string[], k: string) => r[head.indexOf(k)];
  return lines
    .slice(1)
    .map((l) => l.split(","))
    .filter((r) => col(r, "economia") === "1" || col(r, "politica") === "1")
    .map((r) => all[col(r, "video_id")])
    .filter(Boolean)
    .map((v) => {
      const p = `${RAW}/captions/${v.id}.json`;
      const cap: Caption | null = existsSync(p) ? JSON.parse(readFileSync(p, "utf8")) : null;
      const captions = cap?.status === "ok" ? (cap.segments ?? []).map((s) => s.t).join(" ").trim() : "";
      return { v, captions };
    });
}

/** Links, hashtags and channel boilerplate carry no ideas: drop them to save tokens. */
function cleanDesc(d: string): string {
  return d
    .split("\n")
    .filter((l) => !/https?:\/\//.test(l) && !/^[\s_#@-]*$/.test(l))
    .join("\n")
    .slice(0, 2500);
}

function userPrompt(x: { v: Video; captions: string }): string {
  return `Título: ${x.v.title}\nDescrição: ${cleanDesc(x.v.description) || "(vazia)"}\nLegendas (começo): ${x.captions || "(sem legendas)"}`;
}

function estimate(list: { v: Video; captions: string }[]): number {
  const p = PRICES[MODEL];
  const sysTok = SYSTEM.length / 3.2;
  const userTok = list.reduce((n, x) => n + userPrompt(x).length / 3.2, 0);
  const outTok = list.length * 250;
  // First call writes the cache; the rest read it.
  const usd = (sysTok * p.cacheWrite + sysTok * (list.length - 1) * p.cacheRead + userTok * p.input + outTok * p.output) / 1e6;
  const noCache = ((sysTok * list.length + userTok) * p.input + outTok * p.output) / 1e6;
  console.log(`${list.length} videos (${list.filter((x) => x.captions).length} with captions) · system ~${Math.round(sysTok)} tok · user ~${Math.round(userTok / 1000)}k tok · out ~${Math.round(outTok / 1000)}k tok`);
  console.log(`estimated $${usd.toFixed(4)} with prompt caching, $${noCache.toFixed(4)} if the cache misses`);
  return noCache;
}

function done(): Map<string, Row> {
  const m = new Map<string, Row>();
  if (!existsSync(RAW_OUT)) return m;
  for (const l of readFileSync(RAW_OUT, "utf8").trim().split("\n").filter(Boolean)) {
    const r = JSON.parse(l) as Row;
    m.set(r.id, r);
  }
  return m;
}

async function run(limit: number) {
  mkdirSync(OUT, { recursive: true });
  const list = videos();
  const prev = done();
  let spent = [...prev.values()].reduce((n, r) => n + r.costUsd, 0);
  const todo = list.filter((x) => !prev.has(x.v.id)).slice(0, limit);
  console.log(`${prev.size} done ($${spent.toFixed(4)}), ${todo.length} to run`);
  const client = new Anthropic({ apiKey: apiKey() });
  let cacheReads = 0;
  let failed = 0;
  let i = 0;
  const worker = async () => {
    while (i < todo.length) {
      if (spent >= STOP_USD) return;
      const x = todo[i++];
      try {
        const m = await client.messages.create({
          model: MODEL,
          max_tokens: 1500,
          thinking: { type: "disabled" },
          output_config: { effort: "low", format: { type: "json_schema", schema: SCHEMA } },
          system: [{ type: "text", text: SYSTEM, cache_control: { type: "ephemeral" } }],
          messages: [{ role: "user", content: userPrompt(x) }],
        });
        const cost = costUsd(MODEL, m.usage);
        spent += cost;
        if (m.usage.cache_read_input_tokens) cacheReads++;
        const text = m.content.find((c) => c.type === "text");
        if (m.stop_reason !== "end_turn" || !text || text.type !== "text") {
          failed++;
          console.log(`  ${x.v.id}: stop ${m.stop_reason}`);
          continue;
        }
        const j = JSON.parse(text.text);
        const row: Row = { id: x.v.id, captions: !!x.captions, ...j, costUsd: cost };
        appendFileSync(RAW_OUT, JSON.stringify(row) + "\n");
      } catch (e) {
        failed++;
        console.log(`  ${x.v.id}: ${e instanceof Error ? e.message.slice(0, 200) : String(e)}`);
      }
    }
  };
  await Promise.all(Array.from({ length: CONCURRENCY }, worker));
  writeFileSync(SPEND, JSON.stringify({ model: MODEL, costUsd: spent, rows: done().size, at: new Date().toISOString() }, null, 1));
  console.log(`ran ${todo.length}, failed ${failed}, cache reads ${cacheReads}, total probe spend $${spent.toFixed(4)}${spent >= STOP_USD ? " (STOPPED at cap)" : ""}`);
}

function report() {
  const rows = [...done().values()];
  const all: Record<string, Video> = JSON.parse(readFileSync(`${RAW}/videos.json`, "utf8"));
  const spent = rows.reduce((n, r) => n + r.costUsd, 0);
  const forbidden = (c: Concept) => FORBIDDEN.includes(looseNorm(c.name)) || FORBIDDEN.includes(looseNorm(c.surface));
  const dropped: Concept[] = [];
  const concepts = rows.flatMap((r) =>
    r.concepts.filter((c) => (forbidden(c) ? (dropped.push(c), false) : true)).map((c) => ({ ...c, video: r.id, captions: r.captions })),
  );
  const withIdeas = rows.filter((r) => r.concepts.length > 0).length;

  // In-graph hits per node (distinct videos).
  const hits = new Map<string, Set<string>>();
  for (const c of concepts) if (c.in_graph !== "none") (hits.get(c.in_graph) ?? hits.set(c.in_graph, new Set()).get(c.in_graph)!).add(c.video);
  const never = KG.nodes.filter((n) => !hits.has(n.id));

  // Alias candidates: in-graph hits whose surface term is not already the node's name or an alias, plus alias_only misses.
  const known = new Map(KG.nodes.map((n) => [n.id, new Set([n.name, ...n.aliases].map(looseNorm))]));
  const aliasCand = new Map<string, { node: string; term: string; videos: Set<string>; ev: string }>();
  for (const c of concepts) {
    const node = c.in_graph !== "none" ? c.in_graph : c.alias_only && c.nearest !== "none" ? c.nearest : null;
    if (!node) continue;
    const term = c.surface.trim() || c.name;
    const t = looseNorm(term);
    if (!t || t.split(" ").length > 5 || FORBIDDEN.some((f) => ` ${t} `.includes(` ${f} `))) continue;
    if ([...known.get(node)!].some((a) => a === t || (a.length > 3 && t.includes(a)))) continue;
    const k = `${node}|${t}`;
    const e = aliasCand.get(k) ?? { node, term, videos: new Set(), ev: c.evidence };
    e.videos.add(c.video);
    aliasCand.set(k, e);
  }

  // Missing concepts, grouped by normalized name.
  type Miss = { name: string; types: Map<string, number>; videos: Set<string>; ev: { q: string; v: string }[]; near: Map<string, number> };
  const miss = new Map<string, Miss>();
  for (const c of concepts) {
    if (c.in_graph !== "none" || c.alias_only) continue;
    const k = looseNorm(c.name);
    const g: Miss = miss.get(k) ?? { name: c.name, types: new Map(), videos: new Set(), ev: [], near: new Map() };
    g.types.set(c.type, (g.types.get(c.type) ?? 0) + 1);
    g.videos.add(c.video);
    if (g.ev.length < 2 && !g.ev.some((e) => e.v === c.video)) g.ev.push({ q: c.evidence, v: c.video });
    if (c.nearest !== "none") {
      const nk = `${c.relation} ${c.nearest}`;
      g.near.set(nk, (g.near.get(nk) ?? 0) + 1);
    }
    miss.set(k, g);
  }
  const top = (m: Map<string, number>) => [...m.entries()].sort((a, b) => b[1] - a[1])[0]?.[0] ?? "";
  const ranked = [...miss.values()].sort((a, b) => b.videos.size - a.videos.size || a.name.localeCompare(b.name));
  const cell = (s: string) => s.replace(/\|/g, "/").replace(/\n/g, " ");
  const vt = (id: string) => cell((all[id]?.title ?? id).slice(0, 60));

  const L: string[] = [];
  const prev = existsSync("eval/coverage-probe.md") ? readFileSync("eval/coverage-probe.md", "utf8") : "";
  if (prev.includes(MARK)) L.push(prev.slice(0, prev.indexOf(MARK)) + MARK, "");
  else L.push("# Knowledge-graph coverage probe", "", MARK, "");
  L.push("## Raw output", "");
  L.push(`Generated by \`scripts/coverage-probe.ts\` with ${MODEL}, graph ${KG.nodes.length} nodes / ${KG.edges.length} edges (p6). Measure only: \`shared/kg.json\` and the prompt are unchanged.`, "");
  L.push("### Inputs and limits", "");
  L.push(`- ${rows.length} videos labelled economia or politica in \`data/classifier/labels.csv\`. ${rows.filter((r) => r.captions).length} had stored captions (first ~3 minutes only); the rest are title + description.`);
  L.push(`- ${withIdeas} videos (${Math.round((100 * withIdeas) / rows.length)}%) yielded at least one concept. Most of the rest are political news with no idea argued in the title or description.`);
  L.push("- Titles and descriptions understate what a full video argues. Treat counts as a ranking, not as frequencies.");
  L.push(`- ${dropped.length} concepts naming a party or active politician were dropped (graph rule).`);
  L.push(`- Spend: $${spent.toFixed(4)}.`, "");

  L.push("### Missing concepts as the model named them, ranked by videos", "");
  L.push("Model's suggestion for where each would attach: `relation node` (the new concept *relation* the node), most common answer.", "");
  L.push("| # | Concept | Type | Videos | Would attach | Example evidence |");
  L.push("|---|---|---|---|---|---|");
  ranked.slice(0, 40).forEach((g, i) => {
    const ev = g.ev.map((e) => `"${cell(e.q)}" (${e.v})`).join("<br>");
    L.push(`| ${i + 1} | ${cell(g.name)} | ${top(g.types)} | ${g.videos.size} | ${top(g.near) || "—"} | ${ev} |`);
  });
  const singles = ranked.slice(40);
  if (singles.length) L.push("", `${singles.length} more concepts, one video each: ${singles.map((g) => cell(g.name)).join("; ")}.`);

  L.push("", "### Existing nodes: hits", "");
  L.push("| Node | Type | Videos |", "|---|---|---|");
  for (const n of [...KG.nodes].sort((a, b) => (hits.get(b.id)?.size ?? 0) - (hits.get(a.id)?.size ?? 0)))
    L.push(`| \`${n.id}\` ${cell(n.name)} | ${n.type} | ${hits.get(n.id)?.size ?? 0} |`);
  L.push("", `Never hit (${never.length}): ${never.map((n) => `\`${n.id}\``).join(", ") || "none"}.`);

  L.push("", "### Alias candidates (terms of 5 words or fewer)", "");
  L.push("Terms the videos use for an existing node that are not yet its name or an alias. Today aliases never reach the model prompt (`kgPromptText()` sends name, summary and claims only).", "");
  L.push("| Node | Term in video | Videos | Evidence |", "|---|---|---|---|");
  for (const a of [...aliasCand.values()].sort((x, y) => y.videos.size - x.videos.size).slice(0, 30))
    L.push(`| \`${a.node}\` | ${cell(a.term)} | ${a.videos.size} | "${cell(a.ev)}" |`);

  L.push("", "### Per video", "", "<details><summary>Concepts per video</summary>", "");
  for (const r of rows.filter((r) => r.concepts.length)) {
    L.push(`- **${r.id}** ${vt(r.id)}: ${r.concepts.filter((c) => !forbidden(c)).map((c) => `${c.name}${c.in_graph !== "none" ? ` (\`${c.in_graph}\`)` : c.alias_only ? " (alias)" : ""}`).join("; ")}`);
  }
  L.push("", "</details>", "");
  writeFileSync("eval/coverage-probe.md", L.join("\n"));
  console.log(`wrote eval/coverage-probe.md: ${rows.length} videos, ${ranked.length} missing concepts, ${never.length} nodes never hit, spend $${spent.toFixed(4)}`);
}

const mode = process.argv[2];
const li = process.argv.indexOf("--limit");
const limit = li > 0 ? Number(process.argv[li + 1]) : Infinity;
if (mode === "--estimate") estimate(videos());
else if (mode === "--run") {
  if (estimate(videos()) > 0.25) throw new Error("estimate over $0.25 without caching: ask first");
  run(limit).catch((e) => {
    console.error(e instanceof Error ? e.message : String(e));
    process.exit(1);
  });
} else if (mode === "--report") report();
else console.log("usage: --estimate | --run [--limit N] | --report");
